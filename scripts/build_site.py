def jload(p: Path, default=None):
    try:
        return json.loads(p.read_text())
    except Exception:
        return default


def fmt(x, n=4):
    try:
        return f"{float(x):.{n}f}"
    except Exception:
        return "—"


def pooled_table(arms: dict, best_key: str | None = None) -> str:
    rows = []
    for name, v in sorted(arms.items(), key=lambda kv: -kv[1]["dti"]):
        mark = ' <span class="pill ok">shipped family</span>' if name == best_key else ""
        rows.append(f"<tr><td><code>{name}</code>{mark}</td><td>{fmt(v['dti'])}</td>"
                    f"<td>{v['mean_px']:.0f}</td><td>{fmt(v['coverage'], 3)}</td>"
                    f"<td>{', '.join(fmt(x, 3) for x in v.get('per_fold', []))}</td></tr>")
    return ("<table><tr><th>arm</th><th>pooled HOLDOUT-DTI</th><th>px / fold</th>"
            "<th>coverage of withheld truth</th><th>per fold NW, NE, SW, SE</th></tr>"
            + "".join(rows) + "</table>")


def ceiling_page(cl: dict) -> str:
    """Render evidence/ceiling.json: the metric's algebra applied to every measured arm."""
    arms = cl.get("arms", {})
    req = cl.get("required_coverage_to_reach", {})
    curve = cl.get("ceiling_curve", {})
    why = cl.get("why_the_incumbents_park_low", {})
    board = cl.get("live_board", {}) or {}
    best = cl.get("shipped_arm", "—")

    def _row(item):
        n, a = item
        tag = ' <span class="pill ok">shipped</span>' if n == best else ""
        return (f"<tr><td><code>{n}</code>{tag}</td>"
                f"<td>{fmt(a['pooled_dti'])}</td><td>{fmt(a['coverage_c'])}</td>"
                f"<td>{fmt(a['waste_w'], 3)}</td><td>{fmt(a['credit_per_unit_mass'], 4)}</td>"
                f"<td>{fmt(a['zero_waste_ceiling'])}</td></tr>")

    rows = "".join(_row(it) for it in sorted(arms.items(), key=lambda kv: -kv[1]["pooled_dti"]))

    req_rows = "".join(
        f"<tr><td>{k}</td><td>{fmt(v['required_c_at_zero_waste'])}</td>"
        f"<td>{fmt(v['required_c_at_our_waste'])}</td><td>{fmt(v['our_c'])}</td>"
        f"<td><span class=\"pill {'ok' if v['reachable_at_our_coverage'] else 'bad'}\">"
        f"{'reachable' if v['reachable_at_our_coverage'] else 'out of reach at this coverage'}"
        f"</span></td></tr>"
        for k, v in req.items())

    return f"""
<h1>Why this project's emissions park at 0.26–0.28</h1>
<p class="dim">A root-cause analysis, computed from <code>evidence/*.json</code> by
<code>scripts/ceiling_analysis.py</code>. Long form: <code>docs/research/why-the-ceiling.md</code>.
Every number here is a <b>holdout</b> number unless it says leaderboard; the only organizer scores
in existence are on the organizer's leaderboard.</p>

<div class="card">
<h3>1 · How the score is computed, in one line</h3>
<p>The published metric is <code>DTI = TP_w / (TP_w + 0.2·FP_w + 0.8·FN_w)</code> with a triangular
300 m kernel. Because <code>FN_w = |G| − TP_w</code> exactly, it is identical to</p>
<p style="font-size:1.15rem"><code>DTI = c / (0.8 + 0.2·c + 0.2·w)</code></p>
<p>with <code>c = TP_w/|G|</code> the <b>credit-weighted coverage</b> (the share of hidden truth the
emission earns) and <code>w = FP_w/|G|</code> the <b>waste</b> in units of the hidden truth count.
The 0.8 term is paid for <i>every</i> hidden pixel whether or not it is found, so coverage is what
pays and waste is a slow tax. One more dot helps exactly when its best kernel weight exceeds
<code>0.2·DTI</code> — the marginal bar, unit-tested in <code>tests/test_metric.py</code>.</p>
</div>

<h2>2 · Every measured family in these coordinates</h2>
<table><tr><th>arm</th><th>pooled DTI</th><th>coverage c</th><th>waste w</th>
<th>credit per unit mass T/S</th><th>best possible score at its own c</th></tr>{rows}</table>
<p>The efficiency column <code>T/S</code> ranks these families in the exact reverse of the score
column: the most efficient emission (the geometry-gated one, T/S = 0.254) scores worst, and the
loosest (τ = 0.05, T/S = 0.088) never climbs either. At this ranking quality, buying coverage costs
waste roughly in proportion, so the score runs along a ridge — and 0.26–0.28 <i>is</i> that ridge.
{why.get('statement','')}</p>

<h2>3 · What would have to change</h2>
<table><tr><th>target DTI</th><th>needed c at zero waste</th><th>needed c at our waste
({fmt(arms.get(best, {}).get('waste_w'), 3)})</th><th>our c</th><th>verdict</th></tr>{req_rows}</table>
<p><b>The live bar is 0.4275</b> ({board.get('top_team', '—')}, read 2026-10-12). With the shipped
arm's coverage, the best score physically reachable is
<b>{fmt(curve.get('zero_waste_ceiling_at_our_coverage'))}</b> — even if not one dot were wasted.
{curve.get('verdict', '')}</p>
<p>So there are two levers, and they are not interchangeable: (a) <b>coverage</b> — a better ranking
of the hidden pixels, worth ≈0.15 of headroom at the shipped coverage; (b) <b>waste</b> — spending
mass where the model's own calibrated probability is highest, with a stopping rule taken from the
marginal bar instead of a swept threshold. Lever (b) is a pure emission change on the existing head;
it is registered as <b>H67-A2</b> in <code>docs/research/hypotheses.md</code> with a ≈0.34 projection
(MODEL projection under the identity above, not a score).</p>

<h2>4 · Two caveats that cut against the pessimism</h2>
<ol>
<li><b>w is an upper bound.</b> The holdout's truth is the withheld <i>catalogue</i>. A dot on a
real, coherent scarp that the catalogue never recorded is scored as pure waste by this instrument —
yet the organizers' Phase-2 labels are built by expert review of Phase-1 submissions (DrivenData
staff, forum thread 11527), so part of that "waste" is the signal the final round rewards.</li>
<li><b>c cannot be forced.</b> Loosening the exposure threshold to τ = 0.05 raises c to 0.508 and
<i>lowers</i> the score to 0.2536, because w grows faster. Order matters: ranking first, packaging
second.</li>
</ol>
"""


